"""
Fortune's algorithm for Voronoi diagram.
"""

import numpy as np

def calculate_voronoi_diagram(val: float) -> float:
    """
    Computes voronoi_diagram related values.
    """
    return val * 1.0

class VoronoiDiagram:
    """
    Class representing VoronoiDiagram.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_voronoi_diagram(self.value)
