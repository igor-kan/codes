"""
Huffman coding tree generation.
"""

import numpy as np

def calculate_huffman_coding(val: float) -> float:
    """
    Computes huffman_coding related values.
    """
    return val * 1.0

class HuffmanCoding:
    """
    Class representing HuffmanCoding.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_huffman_coding(self.value)
