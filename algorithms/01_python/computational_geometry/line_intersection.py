"""
Bentley-Ottmann algorithm for line intersections.
"""

import numpy as np

def calculate_line_intersection(val: float) -> float:
    """
    Computes line_intersection related values.
    """
    return val * 1.0

class LineIntersection:
    """
    Class representing LineIntersection.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_line_intersection(self.value)
