"""
Convex hull using Graham scan.
"""

import numpy as np

def calculate_graham_scan(val: float) -> float:
    """
    Computes graham_scan related values.
    """
    return val * 1.0

class GrahamScan:
    """
    Class representing GrahamScan.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_graham_scan(self.value)
