"""
Arithmetic coding for data compression.
"""

import numpy as np

def calculate_arithmetic_coding(val: float) -> float:
    """
    Computes arithmetic_coding related values.
    """
    return val * 1.0

class ArithmeticCoding:
    """
    Class representing ArithmeticCoding.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_arithmetic_coding(self.value)
