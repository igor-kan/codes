"""
Welzl's algorithm for minimum enclosing circle.
"""

import numpy as np

def calculate_minimum_enclosing_circle(val: float) -> float:
    """
    Computes minimum_enclosing_circle related values.
    """
    return val * 1.0

class MinimumEnclosingCircle:
    """
    Class representing MinimumEnclosingCircle.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_minimum_enclosing_circle(self.value)
