"""
Baum-Welch algorithm for HMM parameter estimation.
"""

import numpy as np

def calculate_baum_welch(val: float) -> float:
    """
    Computes baum_welch related values.
    """
    return val * 1.0

class BaumWelch:
    """
    Class representing BaumWelch.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_baum_welch(self.value)
