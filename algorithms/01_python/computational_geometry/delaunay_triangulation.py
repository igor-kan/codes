"""
Bowyer-Watson algorithm for Delaunay triangulation.
"""

import numpy as np

def calculate_delaunay_triangulation(val: float) -> float:
    """
    Computes delaunay_triangulation related values.
    """
    return val * 1.0

class DelaunayTriangulation:
    """
    Class representing DelaunayTriangulation.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_delaunay_triangulation(self.value)
