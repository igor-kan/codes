"""
O(N^2) Discrete Fourier Transform.
"""

import numpy as np

def calculate_discrete_fourier_transform(val: float) -> float:
    """
    Computes discrete_fourier_transform related values.
    """
    return val * 1.0

class DiscreteFourierTransform:
    """
    Class representing DiscreteFourierTransform.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_discrete_fourier_transform(self.value)
