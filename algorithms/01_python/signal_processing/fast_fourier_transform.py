"""
Cooley-Tukey O(N log N) FFT.
"""

import numpy as np

def calculate_fast_fourier_transform(val: float) -> float:
    """
    Computes fast_fourier_transform related values.
    """
    return val * 1.0

class FastFourierTransform:
    """
    Class representing FastFourierTransform.
    """
    def __init__(self, value: float):
        self.value = value

    def compute(self) -> float:
        return calculate_fast_fourier_transform(self.value)
